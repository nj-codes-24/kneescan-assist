"""
build_deploy.py: pack the demo app into a folder (and a zip) that builds into a container for the public "live demo".

What it does
    Writes export/deploy/ (git-ignored) and export/kneescan-deploy.zip with:
      Dockerfile, .dockerignore  how to build the container: Python 3.11, CPU-only PyTorch, the app, run as a normal user
      requirements.txt           CPU-only PyTorch plus exactly what the app imports (Gradio pinned to the tested version)
      app/, kneescan/            the code, copied unchanged (no tests, scripts, data or weights)
      configs/app.yaml           configs/app.yaml with configs/deploy.yaml merged over it (hosted wording, weights repo, sample)
      samples/kneemri/           one KneeMRI volume, copied UNCHANGED from the .pck into .npy (a format change only), and credits
      README.md                  what the folder is, credits and the disclaimer
    The weights are not in the folder: the container downloads them at start-up from the private model repo in configs/deploy.yaml.

Why these rules? (decisions D-025, D-026)
    * No MRNet scan may be shown publicly (MRNet RUA clause 4), so the example study is a KneeMRI exam.
    * KneeMRI is CC BY-NC-ND 4.0: sharing a verbatim copy with credits is allowed, a converted or cropped copy is not.
      So the volume keeps its original size, intensities and slice order; the app does the usual preprocessing at run time.
    * The weights stay private (MRNet-trained); only the running app can read them.
    * A container runs the same anywhere: Azure Container Apps today, another host tomorrow.

Alternatives
    With permission to share the weights, you'd copy them into the image and drop the token.

Usage (from the repo root; -I because it opens a KneeMRI .pck file)
    .venv\\Scripts\\python.exe -I scripts\\build_deploy.py
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

import numpy as np
import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from kneescan.data.kneemri import index_volumes, safe_load_pck  # noqa: E402

DEPLOY_DIR = REPO_ROOT / "export" / "deploy"
CODE_DIRS = ("app", "kneescan")
DEPLOY_ONLY_KEYS = {"kneemri_sample"}
REQUIREMENTS = """# CPU-only PyTorch: the server has no GPU, and the CPU wheels are much smaller.
--extra-index-url https://download.pytorch.org/whl/cpu
torch==2.8.0
torchvision==0.23.0
numpy>=1.26,<3
scipy>=1.11
pandas>=2.2,<3
scikit-learn>=1.4,<2
timm>=1.0,<1.1
pyyaml>=6.0
tqdm>=4.66
matplotlib>=3.8
pydicom>=2.4
gradio=={gradio_version}
"""
DOCKERFILE = """# KneeScan Assist demo container (built by scripts/build_deploy.py). Research prototype, not a medical device.
FROM python:3.11-slim

# No .pyc files, logs straight to the console, no Gradio usage statistics, 2 CPU threads (the server has 2 vCPUs),
# and fewer malloc arenas so memory freed by one analysis is reused by the next.
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 GRADIO_ANALYTICS_ENABLED=False OMP_NUM_THREADS=2 MALLOC_ARENA_MAX=2 \\
    HF_HOME=/tmp/hf HF_HUB_DISABLE_TELEMETRY=1

WORKDIR /srv
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . .

# Run as an ordinary user, not root.
RUN useradd --create-home kneescan && chown -R kneescan /srv
USER kneescan

EXPOSE 7860
CMD ["python", "app/clinic_app.py"]
"""
DOCKERIGNORE = "**/__pycache__\n**/*.pyc\n*.zip\n"
README = """# KneeScan Assist: deploy folder

Generated by `scripts/build_deploy.py` from https://github.com/nj-codes-24/kneescan-assist. Build it with the Dockerfile; the
running app downloads its weights from a private Hugging Face repo, using the `HF_TOKEN` environment variable.
See docs/HOSTING.md in the code repository.

**Research prototype, not a medical device.** For research and education only, not for diagnosis or treatment.

- Model trained on MRNet. This research used data provided by the Stanford Center for Artificial Intelligence in Medicine
  and Imaging (AIMI).
- Example study: KneeMRI (Clinical Hospital Centre Rijeka; Štajduhar et al. 2017), CC BY-NC-ND 4.0. See
  `samples/kneemri/CREDITS.md`.
"""
SAMPLE_CREDITS = """# Example study: credits and licence

`sagittal_kneemri_{exam}.npy` is one volume of the **KneeMRI** dataset, copied unchanged from its original `.pck` file
(same voxels, size and slice order; only the file format differs).

- Source: Clinical Hospital Centre Rijeka, Croatia. Dataset: https://zenodo.org/records/14789903
- Paper: Štajduhar I, Mamula M, Miletić D, Ünal G. Semi-automated detection of anterior cruciate ligament injury from MRI.
  Computer Methods and Programs in Biomedicine 140:151–164, 2017. https://doi.org/10.1016/j.cmpb.2016.12.006
- Licence: CC BY-NC-ND 4.0, https://creativecommons.org/licenses/by-nc-nd/4.0/ (non-commercial use only)
- Diagnosis recorded in the dataset: complete ACL tear.
"""


def deploy_settings(app_yaml: Path, deploy_yaml: Path) -> tuple[dict, dict]:
    """(settings the hosted app reads, build-only settings) from the two config files."""
    merged = {**yaml.safe_load(app_yaml.read_text(encoding="utf-8")),
              **yaml.safe_load(deploy_yaml.read_text(encoding="utf-8"))}
    build_only = {k: merged.pop(k) for k in DEPLOY_ONLY_KEYS}
    return merged, build_only


def copy_code(dest: Path) -> None:
    for name in CODE_DIRS:
        shutil.copytree(REPO_ROOT / name, dest / name, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def export_sample(exam_file: str, dest: Path) -> Path:
    """The KneeMRI volume as-is: same array, saved as .npy (the app reads the plane from the file name)."""
    volume = safe_load_pck(index_volumes(REPO_ROOT / "data" / "kneemri" / "volumes")[exam_file])
    exam = Path(exam_file).stem
    dest.mkdir(parents=True, exist_ok=True)
    out = dest / f"sagittal_kneemri_{exam}.npy"
    np.save(out, volume, allow_pickle=False)
    (dest / "CREDITS.md").write_text(SAMPLE_CREDITS.format(exam=exam), encoding="utf-8")
    return out


def write_text(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")      # Linux line endings inside the container


def build(dest: Path = DEPLOY_DIR) -> Path:
    import gradio
    if dest.exists():
        shutil.rmtree(dest)          # only ever our own generated folder under export/
    settings, build_only = deploy_settings(REPO_ROOT / "configs" / "app.yaml", REPO_ROOT / "configs" / "deploy.yaml")
    copy_code(dest)
    (dest / "configs").mkdir()
    write_text(dest / "configs" / "app.yaml",
               "# Hosted demo settings, generated by scripts/build_deploy.py from configs/app.yaml + configs/deploy.yaml\n"
               + yaml.safe_dump(settings, sort_keys=False, allow_unicode=True))
    write_text(dest / "requirements.txt", REQUIREMENTS.format(gradio_version=gradio.__version__))
    write_text(dest / "Dockerfile", DOCKERFILE)
    write_text(dest / ".dockerignore", DOCKERIGNORE)
    write_text(dest / "README.md", README)
    export_sample(build_only["kneemri_sample"], dest / settings["sample_dir"])
    shutil.make_archive(str(dest.parent / "kneescan-deploy"), "zip", root_dir=dest)
    return dest


def main() -> None:
    dest = build()
    size_mb = sum(p.stat().st_size for p in dest.rglob("*") if p.is_file()) / 1e6
    print(f"Deploy folder ready: {dest} ({size_mb:.1f} MB), zipped as {dest.parent / 'kneescan-deploy.zip'}. "
          "Weights are read from the private model repo at start-up.")


if __name__ == "__main__":
    main()
